async function main() {
  console.log("🌱 Начинаем заполнение базы данных...");

  for (const cat of categories) {
    const { subcategories: subs, tips: catTips, ...catData } = cat;

    const category = await prisma.category.upsert({
      where: { slug: catData.slug },
      update: catData,
      create: catData,
    });

    console.log(`✅ Категория: ${category.name}`);

    for (let i = 0; i < catTips.length; i++) {
      await prisma.tip.create({
        data: {
          ...catTips[i],
          categoryId: category.id,
          order: i,
        },
      });
    }

    for (let i = 0; i < subs.length; i++) {
      await prisma.subcategory.upsert({
        where: {
          slug_categoryId: { slug: subs[i].slug, categoryId: category.id },
        },
        update: { ...subs[i], categoryId: category.id, order: i },
        create: { ...subs[i], categoryId: category.id, order: i },
      });
    }
  }

  console.log("🎉 База данных заполнена успешно!");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
